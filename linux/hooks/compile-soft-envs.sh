#!/bin/sh
# shellcheck disable=SC2016

#? extracts package identifiers from nix/shared/lists/*.nix into bash var assignments
#? for ubuntu and termux bootstrap in setup.sh:
#? - common packages (identical names in ubuntu/termux) stay in soft_unix / soft_base / soft_add
#? - differing packages go into soft_add_ubuntu and soft_add_termux

extract_envs() {
  awk '
    {
      line = $0
      sub(/^[ \t]+/, "", line)
      sub(/[ \t]+$/, "", line)
      if (inOverride) {
        if (line ~ /^\}\)[,;]?[ \t]*(#.*)?$/) inOverride = 0
        next
      }
      if (line == "" || line ~ /^#/) next
      if (line == "{" || line == "}" || line == "[" || line == "]" || line ~ /^with pkgs;/ || line ~ /^\{ pkgs/) next
      ident = line
      sub(/[ \t]*#.*/, "", ident)
      if (ident == "") next
      if (ident ~ /^\([A-Za-z0-9_.+-]+\.override[ \t]*\{/) {
        sub(/^\(/, "", ident)
        sub(/\.override[ \t]*\{.*/, "", ident)
        if (line !~ /\}\)[,;]?[ \t]*(#.*)?$/) inOverride = 1
      }

      split("", marker)
      rem = line
      while (match(rem, /# \* [a-zA-Z0-9_-]+:[^#]*/)) {
        m = substr(rem, RSTART, RLENGTH)
        rem = substr(rem, RSTART + RLENGTH)
        sub(/^# \* /, "", m)
        t = m
        sub(/:.*/, "", t)
        v = m
        sub(/^[^:]*:/, "", v)
        sub(/^[ \t]+/, "", v)
        sub(/[ \t]+$/, "", v)
        marker[t] = v
      }

      u_val = ("ubuntu" in marker ? marker["ubuntu"] : ("apt" in marker ? marker["apt"] : ident))
      t_val = ("termux" in marker ? marker["termux"] : ("apt" in marker ? marker["apt"] : ident))

      if (u_val == t_val) {
        if (u_val != "-") {
          if (FILENAME ~ /00_essential\.nix$/) unix = unix " " u_val
          else if (FILENAME ~ /01_base\.nix$/) base = base " " u_val
          else if (FILENAME ~ /02_add\.nix$/) add = add " " u_val
        }
      } else {
        if (u_val != "" && u_val != "-") add_ubuntu = add_ubuntu " " u_val
        if (t_val != "" && t_val != "-") add_termux = add_termux " " t_val
      }
    }

    END {
      sub(/^[ \t]+/, "", unix)
      sub(/^[ \t]+/, "", base)
      sub(/^[ \t]+/, "", add)
      sub(/^[ \t]+/, "", add_ubuntu)
      sub(/^[ \t]+/, "", add_termux)
      printf "soft_envs() {\n"
      printf "  soft_unix=\047%s\047\n", unix
      printf "  soft_base=\047%s\047\n", base
      printf "  soft_add=\047%s\047\n", add
      printf "  soft_add_ubuntu=\047%s\047\n", add_ubuntu
      printf "  soft_add_termux=\047%s\047\n", add_termux
      printf "}\n"
    }
  ' "$@"
}

{
  echo "#!/bin/sh"
  echo
  echo "#? THIS FILE WAS AUTOGENERATED WITH PRE-COMMIT HOOK"
  echo
  extract_envs ./nix/shared/lists/00_essential.nix ./nix/shared/lists/01_base.nix ./nix/shared/lists/02_add.nix
  echo
} > ./linux/.config/shell/soft-envs.sh

chmod +x ./linux/.config/shell/soft-envs.sh
git add ./linux/.config/shell/soft-envs.sh
